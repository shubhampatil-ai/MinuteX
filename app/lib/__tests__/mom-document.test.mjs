describe("DOCX — the package", () => {
  it("is a real zip with the parts Word needs", () => {
    const files = unzipSync(buildMomDocx(FULL));
    for (const part of ["[Content_Types].xml", "word/document.xml", "word/footer1.xml"]) {
      assert.ok(files[part], `missing ${part}`);
    }
  });

  it("declares the footer part, so the page number is not a dangling ref", () => {
    const files = unzipSync(buildMomDocx(FULL));
    assert.match(strFromU8(files["[Content_Types].xml"]), /footer1\.xml/);
    assert.match(docxBody(FULL), /<w:footerReference/);
  });

  it("uses a real PAGE field rather than a number we invented", () => {
    const files = unzipSync(buildMomDocx(FULL));
    assert.match(strFromU8(files["word/footer1.xml"]), /instrText[^>]*>PAGE</);
  });

  it("has one well-formed body with page size and margins", () => {
    const xml = docxBody(FULL);
    assert.equal((xml.match(/<w:body>/g) ?? []).length, 1);
    assert.match(xml, new RegExp(`<w:pgSz w:w="${twips(8.5)}" w:h="${twips(11)}"`));
    assert.match(xml, new RegExp(`w:top="${twips(0.9)}"`));
  });

  it("opens every tag it closes in the table markup", () => {
    const xml = docxBody(FULL);
    for (const tag of ["w:tbl", "w:tr", "w:tc", "w:p", "w:r"]) {
      const open = (xml.match(new RegExp(`<${tag}[ >]`, "g")) ?? []).length;
      const close = (xml.match(new RegExp(`</${tag}>`, "g")) ?? []).length;
      assert.equal(open, close, `${tag}: ${open} open vs ${close} close`);
    }
  });
});

describe("DOCX — content reaches the file", () => {
  it("carries the masthead, every section title and every value", () => {
    const xml = docxBody(FULL);
    assert.ok(xml.includes("Exceller Tech"));
    assert.ok(xml.includes("Minutes of Meeting"));
    assert.ok(xml.includes("Internal Task Portal"));
    for (const text of ["Meeting Details", "19 August 2026", "Action Items",
                        "Complete OAuth integration", "Rohan", "Highlights",
                        "OAuth is nearly done", "Summary",
                        "The team reviewed progress."]) {
      assert.ok(xml.includes(text), `missing: ${text}`);
    }
  });

  it("exports the USER's text, not the AI's original", () => {
    // The end of the chain the backend's merge protects.
    const edited = mom([
      { id: "s_s", kind: "text", title: "Summary", visible: true,
        source: "user_edited", role: "summary",
        text: "Complete OAuth integration and test Salesforce connection." },
    ]);
    const xml = docxBody(edited);
    assert.ok(xml.includes("test Salesforce connection"));
  });

  it("omits hidden sections, rows and fields", () => {
    const hidden = mom([
      { ...FULL.sections[0], fields: [
        { ...FULL.sections[0].fields[0], visible: false },
        FULL.sections[0].fields[1],
      ] },
      { ...FULL.sections[1], rows: [
        { ...FULL.sections[1].rows[0], visible: false },
        FULL.sections[1].rows[1],
      ] },
      { ...FULL.sections[3], visible: false },
    ]);
    const xml = docxBody(hidden);
    assert.equal(xml.includes("19 August 2026"), false);
    assert.ok(xml.includes("3:30 PM"));
    assert.equal(xml.includes("Complete OAuth integration"), false);
    assert.ok(xml.includes("Write the migration script"));
    assert.equal(xml.includes("The team reviewed progress."), false);
  });

  it("drops a section whose content is entirely empty, heading included", () => {
    const xml = docxBody(mom([
      { id: "s_e", kind: "list", title: "Decisions", visible: true,
        source: "ai", role: "decisions", items: [] },
      FULL.sections[3],
    ]));
    assert.equal(xml.includes("Decisions"), false);
    assert.ok(xml.includes("Summary"));
  });

  it("renders section order as the user arranged it", () => {
    const reordered = mom([FULL.sections[1], FULL.sections[0]]);
    const xml = docxBody(reordered);
    assert.ok(xml.indexOf("Action Items") < xml.indexOf("Meeting Details"));
  });

  it("an empty MoM still produces a valid document", () => {
    const xml = docxBody(mom([]));
    assert.match(xml, /<w:body>/);
    assert.ok(xml.includes("no visible content"));
  });
});

describe("DOCX — tables that span pages, and text that could clip", () => {
  it("marks the header row to repeat across a page break", () => {
    // Without tblHeader, page 2 of a long table is unlabelled cells.
    assert.match(docxBody(FULL), /<w:trPr><w:tblHeader\/><\/w:trPr>/);
  });

  it("keeps every row of a long table", () => {
    const big = table("big", "Action Items", ["Sr. No", "Action Item", "Owner"],
      Array.from({ length: 60 }, (_, i) => [String(i + 1), `Task number ${i}`, `Owner ${i}`]));
    const xml = docxBody(mom([big]));
    assert.ok(xml.includes("Task number 0"));
    assert.ok(xml.includes("Task number 59"));
    // header + 60 body rows
    assert.equal((xml.match(/<w:tr>/g) ?? []).length, 61);
  });

  it("keeps every attendee when there are many", () => {
    const many = table("att", "Attendees", ["Sr. No", "Name", "Role / Contribution"],
      Array.from({ length: 40 }, (_, i) => [String(i + 1), `Person ${i}`, "Contributed"]));
    const xml = docxBody(mom([many]));
    assert.ok(xml.includes("Person 0"));
    assert.ok(xml.includes("Person 39"));
  });

  it("column widths always sum to the text column, whatever the headers", () => {
    // A total wider than the page is what pushes the last column off the sheet.
    for (const labels of [
      ["Sr. No", "Discussion Point", "Action Item", "Owner", "Deadline"],
      ["A"], ["Sr. No", "Owner"],
      ["Sr. No", "Topic", "Discussion Point", "Action Item", "Owner", "Deadline"],
    ]) {
      const widths = columnWeights(labels)
        .map((w) => Math.max(400, Math.round(w * CONTENT_WIDTH_TWIPS)));
      const total = widths.reduce((a, b) => a + b, 0);
      assert.ok(total <= CONTENT_WIDTH_TWIPS + labels.length,
        `${labels.length} columns overflow: ${total} > ${CONTENT_WIDTH_TWIPS}`);
      for (const w of widths) assert.ok(w >= 400, "a column too narrow to read");
    }
  });

  it("gives a prose column more room than an index column", () => {
    const labels = ["Sr. No", "Discussion Point", "Owner"];
    const [no, point, owner] = columnWeights(labels);
    assert.ok(point > owner, "prose should be widest");
    assert.ok(owner > no, "an index column should be narrowest");
  });

  it("a very long cell is kept whole rather than truncated", () => {
    const long = "x".repeat(4000);
    const xml = docxBody(mom([table("l", "Notes", ["Detail"], [[long]])]));
    assert.ok(xml.includes(long), "cell text was truncated");
  });

  it("a newline in a cell becomes a paragraph break, not a broken run", () => {
    const xml = docxBody(mom([table("n", "Notes", ["Detail"], [["one\ntwo"]])]));
    assert.ok(xml.includes("one"));
    assert.ok(xml.includes("two"));
    assert.equal(xml.includes("one\ntwo"), false);
  });

  it("keeps a heading with the content beneath it", () => {
    // keepNext stops a heading being orphaned at the foot of a page.
    assert.match(docxBody(FULL), /<w:keepNext\/>/);
  });
});

describe("DOCX — text is escaped, never injected", () => {
  it("escapes XML metacharacters in cells, titles and values", () => {
    const nasty = mom([
      table("x", "Risks & <Issues>", ["Detail"], [['A & B <tag> "q" \'s\'']]),
    ]);
    const xml = docxBody(nasty);
    assert.ok(xml.includes("A &amp; B &lt;tag&gt;"));
    assert.equal(/<tag>/.test(xml), false, "raw tag reached the XML");
    assert.ok(xml.includes("Risks &amp; &lt;Issues&gt;"));
  });

  it("a closing tag typed into a cell cannot end the document", () => {
    const xml = docxBody(mom([
      table("y", "Notes", ["Detail"], [["</w:t></w:r></w:p></w:body>"]]),
    ]));
    assert.equal((xml.match(/<\/w:body>/g) ?? []).length, 1);
    assert.ok(xml.includes("&lt;/w:t&gt;"));
  });

  it("preserves leading and trailing spaces in a run", () => {
    const xml = docxBody(mom([table("z", "Notes", ["Detail"], [["  padded  "]])]));
    assert.match(xml, /<w:t xml:space="preserve">/);
  });
});

describe("PDF HTML", () => {
  it("carries the same content as the DOCX", () => {
    const html = momHtml(FULL, "Meeting");
    for (const text of ["Exceller Tech", "Minutes of Meeting", "Meeting Details",
                        "19 August 2026", "Action Items", "Complete OAuth integration",
                        "Rohan", "OAuth is nearly done", "The team reviewed progress."]) {
      assert.ok(html.includes(text), `missing: ${text}`);
    }
  });

  it("repeats the table header across pages", () => {
    const html = momHtml(FULL, "Meeting");
    assert.match(html, /<thead>/);
    assert.match(html, /thead \{ display: table-header-group; \}/);
  });

  it("lets a long table BREAK across pages", () => {
    // page-break-inside: avoid on a whole grid is what pushes a 60-row table
    // off the sheet. Rows avoid breaking; the table itself must not.
    const html = momHtml(FULL, "Meeting");
    assert.match(html, /\.grid tr \{ page-break-inside: avoid/);
    assert.equal(/table \{[^}]*page-break-inside:\s*avoid/.test(html), false);
  });

  it("sets a real page size and margins", () => {
    const html = momHtml(FULL, "Meeting");
    assert.match(html, /@page \{ size: 8\.5in 11in; margin: 0\.9in; \}/);
  });

  it("wraps a long unbroken string instead of letting it overflow", () => {
    assert.match(momHtml(FULL, "Meeting"), /word-break: break-word/);
  });

  it("escapes HTML in content", () => {
    const html = momHtml(mom([
      table("x", "Notes", ["Detail"], [["<script>alert(1)</script>"]]),
    ]), "Meeting");
    assert.equal(html.includes("<script>"), false);
    assert.ok(html.includes("&lt;script&gt;"));
  });

  it("renders every row of a long table", () => {
    const big = table("big", "Action Items", ["Sr. No", "Action Item", "Owner"],
      Array.from({ length: 60 }, (_, i) => [String(i + 1), `Task ${i}`, `Owner ${i}`]));
    const html = momHtml(mom([big]), "Meeting");
    assert.ok(html.includes("Task 0"));
    assert.ok(html.includes("Task 59"));
    assert.equal((html.match(/<tr>/g) ?? []).length, 61);
  });

  it("column widths sum to 100%", () => {
    const html = momHtml(FULL, "Meeting");
    const widths = [...html.matchAll(/width:([\d.]+)%/g)].map((m) => Number(m[1]));
    assert.ok(widths.length >= 3);
    const total = widths.slice(0, 3).reduce((a, b) => a + b, 0);
    assert.ok(Math.abs(total - 100) < 0.1, `columns sum to ${total}%`);
  });

  it("an empty MoM still produces a valid page", () => {
    const html = momHtml(mom([]), "Meeting");
    assert.match(html, /<!DOCTYPE html>/);
    assert.ok(html.includes("no visible content"));
  });
});

