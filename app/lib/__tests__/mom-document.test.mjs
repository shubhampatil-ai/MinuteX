// lib/__tests__/mom-document.test.mjs — the generated DOCX and PDF-HTML.
//
// Run:  node --test lib/__tests__/mom-document.test.mjs
//
// WHAT THIS PINS. These two renderers produce the artefact the user actually
// sends to other people, and a fault in either is invisible until someone
// opens the file. So the tests are about the failures that do not announce
// themselves:
//
//   CONTENT LOSS — every visible row, field, attendee and list item must
//     reach the output. A table that silently drops its 40th row still opens
//     fine in Word.
//
//   THE USER'S TEXT, NOT THE AI'S — the export must carry what the user
//     edited. This is the end of the chain the backend's merge protects, and
//     the only place it can still be lost.
//
//   INJECTION AND BREAKAGE — a pipe, an angle bracket or an ampersand in a
//     cell must not corrupt the table or inject markup. Cell text is user
//     input and can be anything.
//
//   TABLES THAT SPAN PAGES — the header row must repeat (OOXML tblHeader /
//     CSS thead), or page 2 of a long Action Items table is unlabelled cells.
//     "No clipping" on a phone-authored document mostly means "the renderer
//     was allowed to break the table", which is why the CSS must NOT set
//     page-break-inside: avoid on a whole grid.
//
// A .docx is a ZIP, so the DOCX assertions unzip it and read word/document.xml
// — checking the bytes are a real package, not just that a function returned
// something. fflate is a project dependency, so no new tooling is needed.
//
// The renderers are TypeScript, so their logic is mirrored below, matching the
// convention in task-insights.test.mjs and mom-model.test.mjs.
import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { unzipSync, strFromU8 } from "fflate";

// --- mirrored from lib/mom-template.ts -------------------------------------

const T = {
  accent: "3E6BFF", accentSoft: "EEF2FF", ink: "12131A", inkDim: "5B6072",
  inkFaint: "9297A8", rule: "E6E9F0", zebra: "F7F8FB",
  titlePt: 22, subtitlePt: 13, headingPt: 12, bodyPt: 10.5, tablePt: 9.5,
  kickerPt: 8, footerPt: 8,
  pageWidthIn: 8.5, pageHeightIn: 11, marginIn: 0.9,
  company: "Exceller Tech",
  footerNote:
    "Generated by MinuteX from the meeting recording. Review before circulating.",
};

const CONTENT_WIDTH_IN = T.pageWidthIn - T.marginIn * 2;
const halfPt = (pt) => Math.round(pt * 2);
const twips = (inches) => Math.round(inches * 1440);
const CONTENT_WIDTH_TWIPS = twips(CONTENT_WIDTH_IN);

function columnWeights(labels) {
  if (!labels.length) return [];
  const weight = (label) => {
    const l = label.trim().toLowerCase();
    if (/^(sr\.?\s*no\.?|s\.?\s*no\.?|#|no\.?|index)$/.test(l)) return 0.55;
    if (/^(owner|name|by|assignee|responsible|status|priority)$/.test(l)) return 1.3;
    if (/^(date|time|deadline|due|when|target)$/.test(l)) return 1.1;
    if (/(point|discussion|description|detail|note|action|item|topic|remark)/.test(l)) return 2.6;
    return 1.6;
  };
  const raw = labels.map(weight);
  const total = raw.reduce((a, b) => a + b, 0);
  return raw.map((w) => w / total);
}

function escapeMarkup(s) {
  return String(s ?? "")
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;").replace(/'/g, "&apos;");
}

function templateDate(d = new Date()) {
  return `${d.getDate()} ${d.toLocaleString("en-GB", { month: "long" })} ${d.getFullYear()}`;
}

// --- mirrored from lib/mom-model.ts ----------------------------------------

function isSectionEmpty(section) {
  switch (section.kind) {
    case "fields":
      return !(section.fields ?? []).some((f) => f.visible && (f.label || f.value));
    case "table":
      return !(section.columns ?? []).length
        || !(section.rows ?? []).some((r) => r.visible);
    case "text":
      return !(section.text ?? "").trim();
    default:
      return !(section.items ?? []).some((i) => i.visible && i.text.trim());
  }
}

// --- mirrored from lib/mom-html.ts -----------------------------------------

function paragraphs(text) {
  return (text || "").split(/\n{2,}/).map((b) => b.trim()).filter(Boolean)
    .map((b) => `<p>${escapeMarkup(b).replace(/\n/g, "<br/>")}</p>`).join("");
}

function fieldsHtml(section) {
  const rows = (section.fields ?? [])
    .filter((f) => f.visible && (f.label || f.value))
    .map((f) => `<tr><th scope="row">${escapeMarkup(f.label)}</th>`
      + `<td>${escapeMarkup(f.value).replace(/\n/g, "<br/>")}</td></tr>`)
    .join("");
  return rows ? `<table class="kv">${rows}</table>` : "";
}

function tableHtml(section) {
  const columns = section.columns ?? [];
  const rows = (section.rows ?? []).filter((r) => r.visible);
  if (!columns.length || !rows.length) return "";
  const cols = columnWeights(columns.map((c) => c.label))
    .map((w) => `<col style="width:${(w * 100).toFixed(2)}%"/>`).join("");
  const head = columns.map((c) => `<th>${escapeMarkup(c.label)}</th>`).join("");
  const body = rows.map((r) => "<tr>" + columns
    .map((c) => `<td>${escapeMarkup(r.cells[c.id] ?? "").replace(/\n/g, "<br/>")}</td>`)
    .join("") + "</tr>").join("");
  return `<table class="grid"><colgroup>${cols}</colgroup>`
    + `<thead><tr>${head}</tr></thead><tbody>${body}</tbody></table>`;
}

function listHtml(section) {
  const items = (section.items ?? [])
    .filter((i) => i.visible && i.text.trim())
    .map((i) => `<li>${escapeMarkup(i.text).replace(/\n/g, "<br/>")}</li>`).join("");
  return items ? `<ul>${items}</ul>` : "";
}

function sectionHtml(section) {
  let body = "";
  if (section.kind === "fields") body = fieldsHtml(section);
  else if (section.kind === "table") body = tableHtml(section);
  else if (section.kind === "text") body = paragraphs(section.text ?? "");
  else body = listHtml(section);
  if (!body) return "";
  return `<section class="sec"><h2>${escapeMarkup(section.title)}</h2>${body}</section>`;
}

function momHtml(mom, meetingTitle) {
  const sections = mom.sections
    .filter((s) => s.visible && !isSectionEmpty(s))
    .map(sectionHtml).filter(Boolean).join("");
  const title = mom.title?.trim() || "Minutes of Meeting";
  const subtitle = mom.subtitle?.trim() || meetingTitle || "";
  const empty = '<section class="sec"><p class="empty">This MoM has no visible '
    + 'content yet. Add a section in the editor to see it here.</p></section>';
  return `<!DOCTYPE html>
<html><head><meta charset="utf-8"/>
<title>${escapeMarkup(title)}</title>
<style>
  @page { size: ${T.pageWidthIn}in ${T.pageHeightIn}in; margin: ${T.marginIn}in; }
  body { font-size: ${T.bodyPt}pt; color: #${T.ink}; }
  h2 { font-size: ${T.headingPt}pt; color: #${T.accent};
       page-break-after: avoid; break-after: avoid; }
  .grid thead th { background: #${T.accent}; color: #fff; }
  .grid td { border: 1px solid #${T.rule}; word-break: break-word; }
  .grid tbody tr:nth-child(even) { background: #${T.zebra}; }
  .grid tr { page-break-inside: avoid; break-inside: avoid; }
  thead { display: table-header-group; }
</style></head><body>
<div class="masthead">
  <p class="kicker">${escapeMarkup(T.company)}</p>
  <h1>${escapeMarkup(title)}</h1>
  ${subtitle ? `<p class="subtitle">${escapeMarkup(subtitle)}</p>` : ""}
</div>
<div class="meta"><span>${escapeMarkup(templateDate())}</span></div>
${sections || empty}
<div class="footer"><span>${escapeMarkup(T.footerNote)}</span></div>
</body></html>`;
}

// --- mirrored from lib/mom-docx.ts -----------------------------------------

function run(text, o = {}) {
  const props = [
    o.bold ? "<w:b/>" : "", o.caps ? "<w:caps/>" : "",
    o.color ? `<w:color w:val="${o.color}"/>` : "",
    o.size ? `<w:sz w:val="${halfPt(o.size)}"/>` : "",
    o.spacing ? `<w:spacing w:val="${o.spacing}"/>` : "",
  ].join("");
  return `<w:r>${props ? `<w:rPr>${props}</w:rPr>` : ""}`
    + `<w:t xml:space="preserve">${escapeMarkup(text)}</w:t></w:r>`;
}

function para(runs, o = {}) {
  const props = [
    o.keepNext ? "<w:keepNext/>" : "",
    o.indent ? `<w:ind w:left="${o.indent}"/>` : "",
    (o.after != null || o.before != null)
      ? `<w:spacing${o.before != null ? ` w:before="${o.before}"` : ""}`
        + `${o.after != null ? ` w:after="${o.after}"` : ""}/>` : "",
    o.border
      ? `<w:pBdr><w:bottom w:val="single" w:sz="${o.borderSize ?? 8}" w:color="${o.border}"/></w:pBdr>`
      : "",
  ].join("");
  return `<w:p>${props ? `<w:pPr>${props}</w:pPr>` : ""}${runs}</w:p>`;
}

function multiline(text, o = {}) {
  const lines = String(text ?? "").split("\n");
  return lines.map((line, i) => para(run(line, o), {
    ...o, after: i === lines.length - 1 ? (o.after ?? 0) : 0,
  })).join("");
}

function cell(content, widthTwips, shade) {
  return `<w:tc><w:tcPr><w:tcW w:w="${widthTwips}" w:type="dxa"/>`
    + (shade ? `<w:shd w:val="clear" w:fill="${shade}"/>` : "")
    + `<w:tcMar><w:top w:w="60" w:type="dxa"/><w:bottom w:w="60" w:type="dxa"/>`
    + `<w:left w:w="90" w:type="dxa"/><w:right w:w="90" w:type="dxa"/></w:tcMar>`
    + `</w:tcPr>${content}</w:tc>`;
}

function gridTable(section) {
  const columns = section.columns ?? [];
  const rows = (section.rows ?? []).filter((r) => r.visible);
  if (!columns.length || !rows.length) return "";
  const widths = columnWeights(columns.map((c) => c.label))
    .map((w) => Math.max(400, Math.round(w * CONTENT_WIDTH_TWIPS)));
  const border = (side) => `<w:${side} w:val="single" w:sz="4" w:color="${T.rule}"/>`;
  const header = `<w:tr><w:trPr><w:tblHeader/></w:trPr>`
    + columns.map((c, i) => cell(
      para(run(c.label, { bold: true, color: "FFFFFF", size: T.kickerPt, caps: true, spacing: 8 }),
        { after: 0 }), widths[i], T.accent)).join("") + `</w:tr>`;
  const body = rows.map((r, ri) => `<w:tr>`
    + columns.map((c, ci) => cell(multiline(r.cells[c.id] ?? "", { size: T.tablePt }),
      widths[ci], ri % 2 === 1 ? T.zebra : undefined)).join("") + `</w:tr>`).join("");
  return `<w:tbl><w:tblPr><w:tblW w:w="${CONTENT_WIDTH_TWIPS}" w:type="dxa"/>`
    + `<w:tblLayout w:type="fixed"/><w:tblBorders>`
    + ["top", "left", "bottom", "right", "insideH", "insideV"].map(border).join("")
    + `</w:tblBorders></w:tblPr>`
    + `<w:tblGrid>${widths.map((w) => `<w:gridCol w:w="${w}"/>`).join("")}</w:tblGrid>`
    + header + body + `</w:tbl>`;
}

function fieldsTable(section) {
  const fields = (section.fields ?? []).filter((f) => f.visible && (f.label || f.value));
  if (!fields.length) return "";
  const labelWidth = Math.round(CONTENT_WIDTH_TWIPS * 0.33);
  const valueWidth = CONTENT_WIDTH_TWIPS - labelWidth;
  const rows = fields.map((f) => `<w:tr>`
    + cell(para(run(f.label, { bold: true, color: T.inkDim, size: T.bodyPt }), { after: 40 }), labelWidth)
    + cell(multiline(f.value, { size: T.bodyPt, after: 40 }), valueWidth) + `</w:tr>`).join("");
  return `<w:tbl><w:tblPr><w:tblW w:w="${CONTENT_WIDTH_TWIPS}" w:type="dxa"/>`
    + `<w:tblLayout w:type="fixed"/>`
    + `<w:tblBorders><w:top w:val="none"/><w:left w:val="none"/>`
    + `<w:bottom w:val="none"/><w:right w:val="none"/>`
    + `<w:insideH w:val="none"/><w:insideV w:val="none"/></w:tblBorders></w:tblPr>`
    + `<w:tblGrid><w:gridCol w:w="${labelWidth}"/><w:gridCol w:w="${valueWidth}"/></w:tblGrid>`
    + rows + `</w:tbl>`;
}

function listParagraphs(section) {
  return (section.items ?? []).filter((i) => i.visible && i.text.trim())
    .map((i) => `<w:p><w:pPr><w:numPr><w:ilvl w:val="0"/><w:numId w:val="1"/>`
      + `</w:numPr><w:spacing w:after="40"/></w:pPr>`
      + run(i.text, { size: T.bodyPt }) + `</w:p>`).join("");
}

function sectionXml(section) {
  let body = "";
  if (section.kind === "fields") body = fieldsTable(section);
  else if (section.kind === "table") body = gridTable(section);
  else if (section.kind === "text") {
    body = (section.text ?? "").split(/\n{2,}/).map((b) => b.trim()).filter(Boolean)
      .map((b) => multiline(b, { size: T.bodyPt, after: 120 })).join("");
  } else body = listParagraphs(section);
  if (!body) return "";
  return para(run(section.title, {
    bold: true, color: T.accent, size: T.headingPt, caps: true, spacing: 12,
  }), { before: 220, after: 90, keepNext: true }) + body + para("", { after: 60 });
}

const CONTENT_TYPES_XML = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>`
  + `<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">`
  + `<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>`
  + `<Override PartName="/word/footer1.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.footer+xml"/>`
  + `</Types>`;

const FOOTER_XML = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>`
  + `<w:ftr xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">`
  + `<w:p>` + run(T.footerNote, { size: T.footerPt, color: T.inkFaint })
  + `<w:r><w:instrText xml:space="preserve">PAGE</w:instrText></w:r>`
  + `</w:p></w:ftr>`;

function documentXml(mom, meetingTitle) {
  const title = mom.title?.trim() || "Minutes of Meeting";
  const subtitle = mom.subtitle?.trim() || meetingTitle || "";
  const masthead =
    para(run(T.company, { color: T.accent, size: T.kickerPt, bold: true, caps: true, spacing: 26 }), { after: 40 })
    + para(run(title, { bold: true, size: T.titlePt }), { after: subtitle ? 20 : 60 })
    + (subtitle
      ? para(run(subtitle, { size: T.subtitlePt, color: T.inkDim, bold: true }),
        { after: 60, border: T.accent, borderSize: 18 })
      : para("", { after: 0, border: T.accent, borderSize: 18 }))
    + para(run(templateDate(), { size: T.kickerPt, color: T.inkFaint }), { before: 80, after: 220 });
  const sections = mom.sections.filter((s) => s.visible && !isSectionEmpty(s))
    .map(sectionXml).join("");
  const body = sections
    || para(run("This MoM has no visible content yet.", { size: T.bodyPt, color: T.inkFaint }));
  const sectPr = `<w:sectPr><w:footerReference w:type="default" r:id="rId3"/>`
    + `<w:pgSz w:w="${twips(T.pageWidthIn)}" w:h="${twips(T.pageHeightIn)}"/>`
    + `<w:pgMar w:top="${twips(T.marginIn)}" w:right="${twips(T.marginIn)}" `
    + `w:bottom="${twips(T.marginIn)}" w:left="${twips(T.marginIn)}" w:footer="${twips(0.45)}"/>`
    + `</w:sectPr>`;
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>`
    + `<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main" `
    + `xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">`
    + `<w:body>${masthead}${body}${sectPr}</w:body></w:document>`;
}

// zipSync is only needed to prove the package round-trips; the real module
// zips the same parts.
import { zipSync, strToU8 } from "fflate";

function buildMomDocx(mom, meetingTitle) {
  return zipSync({
    "[Content_Types].xml": strToU8(CONTENT_TYPES_XML),
    "word/document.xml": strToU8(documentXml(mom, meetingTitle)),
    "word/footer1.xml": strToU8(FOOTER_XML),
  }, { level: 6 });
}

/** Unzip a generated .docx and return word/document.xml as text. */
function docxBody(mom, meetingTitle = "Meeting") {
  const files = unzipSync(buildMomDocx(mom, meetingTitle));
  assert.ok(files["word/document.xml"], "package has no document part");
  return strFromU8(files["word/document.xml"]);
}

