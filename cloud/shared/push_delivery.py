"""push_delivery.py — OS push notifications through Expo Push Service.

WHERE THIS SITS. notification_schema.py reserved CHANNEL_PUSH as "the seam":
the in-app notification is the record, and push is a DELIVERY CHANNEL for
one of those records. This module is that channel and nothing else — it does
not decide WHEN to notify (the event sites do, exactly as for in-app) and it
does not invent a second notification vocabulary.

    transcribeRecording  --(brief is ready: AI_OUTPUT_READY row written)-->
    push_delivery.send_to_user()  -->  Expo Push Service  -->  FCM / APNs

WHY A SHARED MODULE. Two Lambdas touch push: userApi registers tokens and
checks delivery receipts; transcribeRecording sends. Both are packaged with
shared/*.py flat at the archive root (scripts/_package_lambda.py), so the
token-row shape, the "is this token usable" rule and the receipt handling
live in one place and cannot drift.

NO AWS AND NO NETWORK IMPORTED HERE. Tables and the HTTP transport are passed
in. That keeps the module testable offline (tests/test_push_notifications.py
drives it with fake tables and a fake transport) and keeps each Lambda the
owner of its own boto3 resource, like notification_schema.

WHAT A PUSH MAY CONTAIN. A fixed title and body, plus IDENTIFIERS for
navigation. Never the meeting title, a summary, a participant name or any
transcript text: a lock screen is readable by whoever is holding the phone,
and the notification payload also transits Expo, Google and Apple. The app
fetches the brief itself — with the user's JWT, re-checking ownership — when
the notification is tapped.

TOKENS ARE PER INSTALLATION, NOT PER USER. One user has as many rows as
devices they signed in on. See scripts/75_create_push_tokens_table.sh for the
key design (PK push_token, GSI user-index) and why.
"""

import json
import re

EXPO_PUSH_URL = "https://exp.host/--/api/v2/push/send"
EXPO_RECEIPTS_URL = "https://exp.host/--/api/v2/push/getReceipts"

# Expo accepts at most 100 messages per send request and 1000 receipt ids per
# receipt request.
SEND_BATCH = 100
RECEIPT_BATCH = 1000

# Expo's own guidance: receipts are generally available ~15 minutes after the
# send, and are kept for about a day. Checking earlier mostly returns nothing.
RECEIPT_MIN_AGE_S = 15 * 60
RECEIPT_MAX_AGE_S = 24 * 3600

# The one push type this phase sends. The value travels in the payload's
# `data.type`, which is what the app's tap handler switches on.
TYPE_BRIEF_READY = "brief_ready"
BRIEF_READY_TITLE = "Brief ready"
BRIEF_READY_BODY = "Your meeting brief is ready to review."

# The Android channel the app creates (lib/push.ts). Must match, or Android
# drops the notification into a default channel the user never configured.
ANDROID_CHANNEL_ID = "briefs"

PLATFORMS = ("ios", "android")

# "ExponentPushToken[xxxxxxxxxxxxxxxxxxxxxx]" (current) or the older
# "ExpoPushToken[...]". Anything else is not something Expo can deliver to, so
# it is rejected at registration rather than stored and failed on forever.
_TOKEN_RE = re.compile(r"^Expo(nent)?PushToken\[[A-Za-z0-9_\-]{8,256}\]$")
# Installation ids are generated by the app (a uuid). Bounded and plain so a
# path parameter can never smuggle anything interesting into a key or a log.
_INSTALLATION_RE = re.compile(r"^[A-Za-z0-9_\-]{8,128}$")
MAX_APP_VERSION = 32

# Expo error codes that mean "this token will never work again". Only these
# deactivate a token; every other error (rate limit, message too big, an Expo
# outage) is about the attempt, not the device, and must not cost the user
# their notifications on that phone.
DEAD_TOKEN_ERRORS = frozenset({"DeviceNotRegistered"})


# ---------------------------------------------------------------------------
# Validation (registration side)
# ---------------------------------------------------------------------------
def is_expo_token(token):
    return isinstance(token, str) and bool(_TOKEN_RE.match(token.strip()))


def is_installation_id(value):
    return isinstance(value, str) and bool(_INSTALLATION_RE.match(value))


def mask_token(token):
    """A log-safe rendering. A push token is a delivery credential for one
    device — anyone holding it can put a notification on that lock screen —
    so logs carry only enough to correlate, never the whole value."""
    t = str(token or "")
    inner = t[t.find("[") + 1:t.rfind("]")] if "[" in t and t.endswith("]") else t
    return f"…{inner[-6:]}" if inner else "…"


def is_deliverable(row):
    """May this token row be sent to? Both flags must agree:

    `enabled`     the USER's brief-ready switch for this device (Settings);
    `invalid_at`  set when Expo reported the token dead. A dead token stays
                  dead until the app registers it again.
    """
    return (isinstance(row, dict)
            and bool(row.get("enabled"))
            and not row.get("invalid_at")
            and is_expo_token(row.get("push_token")))


def public_token(row):
    """The client-facing shape. Assembled (never a copy of the row), so a new
    internal attribute — pending receipt ids, an invalidation reason — cannot
    leak by being forgotten in a deny-list. The token itself is omitted: the
    client already has it, and echoing it teaches nothing."""
    return {
        "installation_id": str(row.get("installation_id") or ""),
        "platform": str(row.get("platform") or ""),
        "enabled": bool(row.get("enabled")),
        "active": not row.get("invalid_at"),
        "updated_at": str(row.get("updated_at") or ""),
    }


# ---------------------------------------------------------------------------
# Payload
# ---------------------------------------------------------------------------
def brief_ready_message(token, recording_key, notification_id=""):
    """The Expo message for "this meeting's brief is ready".

    `recording_key` is the audio_s3_key — the id the app's existing detail
    route (/recording/[key]) opens. `notification_id` is the in-app row this
    push delivers, so tapping the push can mark THAT row read and the bell
    agrees with what the user just did.

    Content is fixed copy on purpose — see the module docstring.
    """
    data = {"type": TYPE_BRIEF_READY, "audio_s3_key": str(recording_key or "")}
    if notification_id:
        data["notification_id"] = str(notification_id)
    return {
        "to": token,
        "title": BRIEF_READY_TITLE,
        "body": BRIEF_READY_BODY,
        "data": data,
        "sound": "default",
        "channelId": ANDROID_CHANNEL_ID,
        # "normal", not "high": this is a productivity notice, not a call.
        # Android may batch it under Doze; the brief is not time-critical to
        # the second.
        "priority": "normal",
    }


# ---------------------------------------------------------------------------
# Transport
# ---------------------------------------------------------------------------
def urllib_transport(timeout=8, access_token=""):
    """The production HTTP POST: stdlib only, like the rest of these Lambdas.

    `access_token` is Expo's optional "enhanced push security" token. When the
    Expo project has that setting on, every send must carry it; when it is
    off, it must be absent. It comes from the Lambda environment, never from
    code or the app.
    """
    import urllib.request  # local: keeps the module import side-effect free

    def post(url, payload):
        headers = {
            "Content-Type": "application/json",
            "Accept": "application/json",
            "Accept-Encoding": "identity",
        }
        if access_token:
            headers["Authorization"] = f"Bearer {access_token}"
        req = urllib.request.Request(
            url, data=json.dumps(payload).encode("utf-8"),
            headers=headers, method="POST")
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return json.loads(resp.read().decode("utf-8") or "{}")
    return post


# ---------------------------------------------------------------------------
# Token table helpers
# ---------------------------------------------------------------------------
def user_rows(tokens_table, user_id, key_cls):
    """Every token row for a user, following pagination (the 1MB page rule —
    see the project memory on list truncation)."""
    rows, start = [], None
    # Bounded: a user has a handful of devices, so 20 pages is already
    # absurd. The bound (and the strict type checks) mean a misbehaving
    # response can never spin this loop forever inside the pipeline Lambda.
    for _ in range(20):
        kw = {"IndexName": "user-index",
              "KeyConditionExpression": key_cls("user_id").eq(user_id)}
        if start:
            kw["ExclusiveStartKey"] = start
        page = tokens_table.query(**kw)
        items = page.get("Items") if isinstance(page, dict) else None
        if isinstance(items, list):
            rows.extend(i for i in items if isinstance(i, dict))
        start = page.get("LastEvaluatedKey") if isinstance(page, dict) else None
        if not isinstance(start, dict) or not start:
            return rows
    print(f"[push] user={user_id}: token pagination bound reached")
    return rows


def deactivate(tokens_table, token, reason, now_iso):
    """Mark ONE token dead. Keeps the row (so the reason is inspectable and a
    re-registration can revive it) but takes it out of delivery."""
    try:
        tokens_table.update_item(
            Key={"push_token": token},
            UpdateExpression="SET invalid_at = :t, invalid_reason = :r, updated_at = :t",
            ConditionExpression="attribute_exists(push_token)",
            ExpressionAttributeValues={":t": now_iso, ":r": str(reason)[:80]},
        )
        return True
    except Exception as err:  # noqa: BLE001 — never fail a delivery over bookkeeping
        print(f"[push] could not deactivate {mask_token(token)}: {type(err).__name__}")
        return False


def _remember_receipts(tokens_table, token, ticket_ids, now_epoch):
    """Park the ticket ids on the token row so a later receipt check can find
    out whether FCM/APNs actually accepted them. Overwrites: only the latest
    send's receipts matter for deciding whether the device is still alive."""
    try:
        tokens_table.update_item(
            Key={"push_token": token},
            UpdateExpression="SET pending_receipts = :ids, pending_since = :t",
            ConditionExpression="attribute_exists(push_token)",
            ExpressionAttributeValues={":ids": list(ticket_ids), ":t": int(now_epoch)},
        )
    except Exception as err:  # noqa: BLE001
        print(f"[push] could not park receipts for {mask_token(token)}: {type(err).__name__}")


def _clear_receipts(tokens_table, token):
    try:
        tokens_table.update_item(
            Key={"push_token": token},
            UpdateExpression="REMOVE pending_receipts, pending_since",
            ConditionExpression="attribute_exists(push_token)",
        )
    except Exception:  # noqa: BLE001
        pass


# ---------------------------------------------------------------------------
# Send
# ---------------------------------------------------------------------------
def send_to_user(tokens_table, user_id, build_message, *, post, key_cls,
                 now_iso, now_epoch):
    """Send one message to every deliverable device of one user.

    `build_message(token)` returns the Expo message for that token, so the
    caller owns the content and this function owns the fan-out.

    NEVER RAISES. It runs after the brief has been persisted and paid for; a
    push failure must not fail the pipeline (which would make S3 retry the
    whole thing). Returns a summary for logs and tests:

        {"devices": n, "accepted": n, "failed": n, "deactivated": n}

    Per-device isolation: one dead token is deactivated and the rest are
    still sent — a batch is never abandoned because one entry in it failed.
    """
    summary = {"devices": 0, "accepted": 0, "failed": 0, "deactivated": 0}
    try:
        rows = [r for r in user_rows(tokens_table, user_id, key_cls) if is_deliverable(r)]
    except Exception as err:  # noqa: BLE001
        print(f"[push] token lookup failed for user={user_id}: {type(err).__name__}: {err}")
        return summary
    summary["devices"] = len(rows)
    if not rows:
        return summary

    for i in range(0, len(rows), SEND_BATCH):
        batch = rows[i:i + SEND_BATCH]
        messages = [build_message(r["push_token"]) for r in batch]
        try:
            resp = post(EXPO_PUSH_URL, messages)
        except Exception as err:  # noqa: BLE001
            # Transport failure: nothing is known about any device, so nothing
            # is deactivated. Logged without the payload or the tokens.
            print(f"[push] send failed for user={user_id} batch={len(batch)}: "
                  f"{type(err).__name__}: {err}")
            summary["failed"] += len(batch)
            continue

        tickets = (resp or {}).get("data")
        if not isinstance(tickets, list) or len(tickets) != len(batch):
            # A request-level error ({"errors": [...]}) or a malformed reply.
            errors = (resp or {}).get("errors")
            print(f"[push] unexpected Expo response for user={user_id}: "
                  f"{json.dumps(errors)[:300] if errors else 'no ticket list'}")
            summary["failed"] += len(batch)
            continue

        # Tickets come back in the SAME ORDER as the messages.
        for row, ticket in zip(batch, tickets):
            token = row["push_token"]
            if isinstance(ticket, dict) and ticket.get("status") == "ok":
                summary["accepted"] += 1
                if ticket.get("id"):
                    _remember_receipts(tokens_table, token, [ticket["id"]], now_epoch)
                continue
            summary["failed"] += 1
            code = ((ticket or {}).get("details") or {}).get("error") or ""
            print(f"[push] ticket error for {mask_token(token)}: "
                  f"{code or 'unknown'} {str((ticket or {}).get('message') or '')[:120]}")
            if code in DEAD_TOKEN_ERRORS:
                if deactivate(tokens_table, token, code, now_iso):
                    summary["deactivated"] += 1

    print(f"[push] user={user_id} devices={summary['devices']} "
          f"accepted={summary['accepted']} failed={summary['failed']} "
          f"deactivated={summary['deactivated']}")
    return summary


# ---------------------------------------------------------------------------
# Receipts
#
# A ticket "ok" only means Expo accepted the message. Whether FCM/APNs then
# rejected the device ("DeviceNotRegistered": the app was uninstalled) is only
# knowable from the RECEIPT, ~15 minutes later. There is no scheduler in this
# architecture, and adding one for this alone is not justified — so receipts
# are checked OPPORTUNISTICALLY: whenever the user's app re-registers its
# token (every app start while signed in), userApi calls check_receipts for
# that user. Receipts are kept by Expo for ~a day; a dead token whose receipt
# expired unread is still caught by the NEXT send's ticket, which carries the
# same error for a device Expo already knows is gone.
# ---------------------------------------------------------------------------
def check_receipts(tokens_table, user_id, *, post, key_cls, now_iso, now_epoch):
    """Resolve parked receipts for one user's tokens. Never raises.

    Returns {"checked": n, "deactivated": n}.
    """
    out = {"checked": 0, "deactivated": 0}
    try:
        rows = user_rows(tokens_table, user_id, key_cls)
    except Exception as err:  # noqa: BLE001
        print(f"[push] receipt lookup failed for user={user_id}: {type(err).__name__}")
        return out

    due = {}
    for r in rows:
        ids = r.get("pending_receipts") or []
        since = int(r.get("pending_since") or 0)
        if not ids or not since:
            continue
        age = now_epoch - since
        if age < RECEIPT_MIN_AGE_S:
            continue
        if age > RECEIPT_MAX_AGE_S:
            # Expo has dropped them; asking is pointless.
            _clear_receipts(tokens_table, r["push_token"])
            continue
        for rid in ids:
            due[str(rid)] = r["push_token"]
    if not due:
        return out

    ids = list(due)
    for i in range(0, len(ids), RECEIPT_BATCH):
        chunk = ids[i:i + RECEIPT_BATCH]
        try:
            resp = post(EXPO_RECEIPTS_URL, {"ids": chunk})
        except Exception as err:  # noqa: BLE001
            print(f"[push] receipt request failed for user={user_id}: {type(err).__name__}")
            return out
        receipts = (resp or {}).get("data") or {}
        if not isinstance(receipts, dict):
            return out
        resolved_tokens = set()
        for rid in chunk:
            receipt = receipts.get(rid)
            if receipt is None:
                continue    # not ready yet — leave it parked
            out["checked"] += 1
            token = due[rid]
            resolved_tokens.add(token)
            if receipt.get("status") == "error":
                code = (receipt.get("details") or {}).get("error") or ""
                print(f"[push] receipt error for {mask_token(token)}: {code or 'unknown'}")
                if code in DEAD_TOKEN_ERRORS and deactivate(tokens_table, token, code, now_iso):
                    out["deactivated"] += 1
        for token in resolved_tokens:
            _clear_receipts(tokens_table, token)
    return out
